#!/usr/bin/env bash
# clusters/hcp-autonode/lib-terraform.sh — Terraform helpers for the AutoNode HCP stack.
# Extends the base HCP lib with AutoNode-specific tfvars (provision_shard_id).
# Sourced from create.sh / destroy.sh after common.sh (fail, info, now_ms, emit_timing).

set -euo pipefail

hcp_terraform_dir() {
  # Stack root: clusters/hcp/terraform/ (alongside lib-terraform.sh).
  cd "$(dirname "${BASH_SOURCE[0]}")/terraform" && pwd
}

ensure_rhcs_token() {
  if [[ -n "${RHCS_TOKEN:-}" ]]; then
    return 0
  fi
  local tok
  if tok="$(rosa token 2>/dev/null)" && [[ -n "${tok}" ]]; then
    export RHCS_TOKEN="${tok}"
    info "Exported RHCS_TOKEN from rosa token for Terraform RHCS provider."
    return 0
  fi
  fail "RHCS_TOKEN is unset and 'rosa token' failed. Run: rosa login   or: export RHCS_TOKEN=<offline token>"
}

hcp_terraform_state_path() {
  local cluster="${1:?}"
  printf '%s/terraform.%s.tfstate\n' "$(hcp_terraform_dir)" "${cluster}"
}

hcp_terraform_generated_varfile() {
  local cluster="${1:?}"
  printf '%s/.generated.%s.tfvars\n' "$(hcp_terraform_dir)" "${cluster}"
}

# Emit a tfvars fragment (non-sensitive only). Admin password is passed via TF_VAR_admin_password_override.
hcp_write_terraform_varfile() {
  local out="${1:?}"
  local cluster="${2:?}"
  local region="${3:?}"
  local ocp_version="${4:?}"
  local multi_az_tf="${5:?}"
  local min_rep="${6:?}"
  local max_rep="${7:?}"
  local vpc_cidr="${8:?}"
  local inst_type="${9:?}"
  local bench_tag="${10:-manual}"

  local ver_line
  if [[ -n "${ocp_version}" ]]; then
    ver_line="openshift_version = \"${ocp_version}\""
  else
    ver_line="openshift_version = null"
  fi

  # main.tf check block: public demo topology only for this root module.
  cat > "${out}" <<EOF
# Generated by clusters/hcp/create.sh — safe to delete after terraform destroy.
cluster_name = "${cluster}"
region       = "${region}"
network_type = "public"
private      = false
zero_egress  = false
vpc_cidr     = "${vpc_cidr}"
multi_az     = ${multi_az_tf}
${ver_line}
default_instance_type = "${inst_type}"
default_min_replicas  = ${min_rep}
default_max_replicas  = ${max_rep}
additional_machine_pools = {}
persists_through_sleep               = true
enable_gitops_bootstrap              = false
enable_persistent_dns_domain          = false
enable_control_plane_log_forwarding  = false
control_plane_log_s3_enabled       = false
enable_audit_logging               = false
enable_cloudwatch_logging          = false
enable_cert_manager_iam             = false
enable_termination_protection      = false
tags = {
  Terraform    = "true"
  Cluster      = "${cluster}"
  BenchmarkRun = "${bench_tag}"
}
EOF
  # AutoNode private preview: inject provision_shard_id when AUTONODE_SHARD_ID is set.
  # The shard restricts cluster placement to the AutoNode-enabled HyperShift management cluster.
  if [[ -n "${AUTONODE_SHARD_ID:-}" ]]; then
    printf 'additional_cluster_properties = { provision_shard_id = "%s" }\n' "${AUTONODE_SHARD_ID}" >> "${out}"
  fi
}

hcp_terraform_cmd() {
  local tf_root
  tf_root="$(hcp_terraform_dir)"
  terraform -chdir="${tf_root}" "$@"
}

# Run terraform apply; retry on CLUSTERS-MGMT-403 (transient OCM race after cluster creation).
# Increments HCP_TF_403_SLEEP_MS_TOTAL across sleeps so benchmarks can emit hcp.ocm403_retry_sleep.
# ROSA_HCP_TERRAFORM_403_MAX_RETRIES  — max attempts (default 12).
# ROSA_HCP_TERRAFORM_403_RETRY_SLEEP_SEC — sleep between retries (default 120 s).
# Returns 0 on success; non-zero on failure (caller records timings then may fail()).
hcp_terraform_apply_retry_on_ocm_403() {
  local varfile="${1:?}"
  shift
  local -a tf_extra=( "$@" )

  local max="${ROSA_HCP_TERRAFORM_403_MAX_RETRIES:-12}"
  [[ "${max}" =~ ^[0-9]+$ ]] || max=12
  (( max >= 1 )) || max=1

  local sleep403="${ROSA_HCP_TERRAFORM_403_RETRY_SLEEP_SEC:-120}"
  [[ "${sleep403}" =~ ^[0-9]+$ ]] || sleep403=120

  local attempt=1
  local log
  log="$(mktemp "${TMPDIR:-/tmp}/hcp-tf-apply.XXXXXX")"
  # shellcheck disable=SC2064
  trap "rm -f '${log}'" RETURN

  while [[ "${attempt}" -le "${max}" ]]; do
    local ec
    set +e
    if ((${#tf_extra[@]} == 0)); then
      hcp_terraform_cmd apply -input=false -auto-approve -var-file="${varfile}" 2>&1 | tee "${log}"
    else
      hcp_terraform_cmd apply -input=false -auto-approve -var-file="${varfile}" "${tf_extra[@]}" 2>&1 | tee "${log}"
    fi
    ec="${PIPESTATUS[0]}"
    set -e

    if [[ "${ec}" -eq 0 ]]; then
      return 0
    fi

    if grep -qE 'CLUSTERS-MGMT-403|Forbidden access to|status is 403[, ]' "${log}"; then
      if [[ "${attempt}" -lt "${max}" ]]; then
        warn "Terraform apply hit transient OCM 403 (attempt ${attempt}/${max}); sleeping ${sleep403}s before retry."
        HCP_TF_403_SLEEP_MS_TOTAL=$(( ${HCP_TF_403_SLEEP_MS_TOTAL:-0} + sleep403 * 1000 ))
        sleep "${sleep403}"
        attempt=$((attempt + 1))
        continue
      fi
      warn "Terraform apply failed with OCM 403 after ${max} attempt(s)."
      return 1
    fi

    return "${ec}"
  done

  return 1
}

# Emit hcp.ocm403_retry_sleep (if any), hcp.terraform_apply, hcp.create_submitted for wall [t0,t1].
_hcp_emit_terraform_apply_timings() {
  local t_apply_0="${1:?}"
  local t_apply_1="${2:?}"
  if [[ "${HCP_TF_403_SLEEP_MS_TOTAL:-0}" -gt 0 ]]; then
    emit_timing "hcp.ocm403_retry_sleep" "$(( t_apply_1 - HCP_TF_403_SLEEP_MS_TOTAL ))" "${t_apply_1}"
  fi
  emit_timing "hcp.terraform_apply" "${t_apply_0}" "${t_apply_1}"
  emit_timing "hcp.create_submitted" "${t_apply_0}" "${t_apply_1}"
}

# Provision cluster via clusters/hcp/terraform: init, apply, timings (hcp.terraform_*, hcp.create_submitted).
hcp_run_terraform_apply() {
  local cluster="${1:?}"
  local resolved_ocp_version="${2:?}"
  local multi_az_tf="${3:?}"
  local replicas_eff="${4:?}"
  local max_replicas="${5:?}"

  command -v terraform >/dev/null 2>&1 || fail "terraform CLI not found. Install Terraform >= 1.5 (see clusters/hcp/terraform/README.md)."

  ensure_rhcs_token

  local tf_root varfile
  tf_root="$(hcp_terraform_dir)"
  [[ -f "${tf_root}/versions.tf" ]] || fail "Missing ${tf_root}/versions.tf — is this repo intact?"

  export TF_VAR_admin_password_override="${CLUSTER_ADMIN_PASSWORD}"

  local vpc_cidr="${ROSA_HCP_NETWORK_VPC_CIDR:-10.0.0.0/16}"
  local inst_type="${ROSA_HCP_INSTANCE_TYPE:-m5.xlarge}"

  if [[ -n "${ROSA_HCP_TERRAFORM_VAR_FILE:-}" ]]; then
    varfile="${ROSA_HCP_TERRAFORM_VAR_FILE}"
    [[ -f "${varfile}" ]] || fail "ROSA_HCP_TERRAFORM_VAR_FILE=${varfile} does not exist."
    info "Using ROSA_HCP_TERRAFORM_VAR_FILE=${varfile} (skipping generated tfvars)."
  else
    varfile="$(hcp_terraform_generated_varfile "${cluster}")"
    local mx="$max_replicas"
    (( mx >= replicas_eff )) || mx="$replicas_eff"
    hcp_write_terraform_varfile "${varfile}" "${cluster}" "${AWS_REGION}" \
      "${resolved_ocp_version}" "${multi_az_tf}" "${replicas_eff}" "${mx}" "${vpc_cidr}" "${inst_type}" \
      "${BENCHMARK_RUN_ID:-manual}"
    ok "Wrote ${varfile}"
  fi

  local state_name="terraform.${cluster}.tfstate"
  local t_init_0 t_init_1 t_apply_0 t_apply_1

  t_init_0="$(now_ms)"
  info "Terraform init (backend path=${state_name})..."
  hcp_terraform_cmd init -input=false -backend-config="path=${state_name}" -reconfigure
  t_init_1="$(now_ms)"
  emit_timing "hcp.terraform_init" "${t_init_0}" "${t_init_1}"

  # Single-shot apply: let the RHCS provider manage internal ordering and waits.
  # The upstream module now passes autoscaling_enabled/min_replicas/max_replicas to
  # rhcs_cluster_rosa_hcp at creation time so the default machine pool reconciliation
  # is a no-op and should not race OCM (see references/validated-pattern-terraform-rosa
  # modules/infrastructure/cluster/10-main.tf lines 223–225).
  # The retry loop is kept as a backstop for any remaining transient OCM 403s.
  HCP_TF_403_SLEEP_MS_TOTAL=0
  t_apply_0="$(now_ms)"
  info "Terraform apply (ROSA HCP modules; this can take 15–30+ minutes)..."
  if ! hcp_terraform_apply_retry_on_ocm_403 "${varfile}"; then
    t_apply_1="$(now_ms)"
    _hcp_emit_terraform_apply_timings "${t_apply_0}" "${t_apply_1}"
    fail "Terraform apply failed. Try: make reconcile-hcp"
  fi
  t_apply_1="$(now_ms)"
  _hcp_emit_terraform_apply_timings "${t_apply_0}" "${t_apply_1}"
}

# Full terraform apply only (same varfile/state as create). For recovery after partial apply — does not init_run.
# Uses single-shot apply (no phased targets) to converge state.
hcp_run_terraform_reconcile_apply() {
  local cluster="${1:?}"
  local resolved_ocp_version="${2:?}"
  local multi_az_tf="${3:?}"
  local replicas_eff="${4:?}"
  local max_replicas="${5:?}"

  command -v terraform >/dev/null 2>&1 || fail "terraform CLI not found."

  ensure_rhcs_token

  local tf_root varfile
  tf_root="$(hcp_terraform_dir)"
  [[ -f "${tf_root}/versions.tf" ]] || fail "Missing ${tf_root}/versions.tf — is this repo intact?"

  export TF_VAR_admin_password_override="${CLUSTER_ADMIN_PASSWORD}"

  local vpc_cidr="${ROSA_HCP_NETWORK_VPC_CIDR:-10.0.0.0/16}"
  local inst_type="${ROSA_HCP_INSTANCE_TYPE:-m5.xlarge}"

  if [[ -n "${ROSA_HCP_TERRAFORM_VAR_FILE:-}" ]]; then
    varfile="${ROSA_HCP_TERRAFORM_VAR_FILE}"
    [[ -f "${varfile}" ]] || fail "ROSA_HCP_TERRAFORM_VAR_FILE=${varfile} does not exist."
    info "Reconcile using ROSA_HCP_TERRAFORM_VAR_FILE=${varfile}"
  else
    varfile="$(hcp_terraform_generated_varfile "${cluster}")"
    local mx="$max_replicas"
    (( mx >= replicas_eff )) || mx="$replicas_eff"
    hcp_write_terraform_varfile "${varfile}" "${cluster}" "${AWS_REGION}" \
      "${resolved_ocp_version}" "${multi_az_tf}" "${replicas_eff}" "${mx}" "${vpc_cidr}" "${inst_type}" \
      "${BENCHMARK_RUN_ID:-manual}"
    ok "Wrote ${varfile}"
  fi

  local state_name="terraform.${cluster}.tfstate"

  info "Terraform init (reconcile; backend path=${state_name})..."
  hcp_terraform_cmd init -input=false -backend-config="path=${state_name}" -reconfigure

  HCP_TF_403_SLEEP_MS_TOTAL=0
  info "Terraform apply (full reconcile, single shot)..."
  if ! hcp_terraform_apply_retry_on_ocm_403 "${varfile}"; then
    fail "Terraform reconcile apply failed after OCM 403 retries."
  fi
  ok "Terraform reconcile apply completed for '${cluster}'."
}

# Destroy infra when local Terraform state exists (same backend path as apply).
hcp_run_terraform_destroy() {
  local cluster="${1:?}"

  command -v terraform >/dev/null 2>&1 || fail "terraform CLI not found."

  ensure_rhcs_token

  local state_name="terraform.${cluster}.tfstate"
  local varfile=""
  if [[ -n "${ROSA_HCP_TERRAFORM_VAR_FILE:-}" ]] && [[ -f "${ROSA_HCP_TERRAFORM_VAR_FILE}" ]]; then
    varfile="${ROSA_HCP_TERRAFORM_VAR_FILE}"
  elif [[ -f "$(hcp_terraform_generated_varfile "${cluster}")" ]]; then
    varfile="$(hcp_terraform_generated_varfile "${cluster}")"
  fi

  if [[ -n "${CLUSTER_ADMIN_PASSWORD:-}" ]]; then
    export TF_VAR_admin_password_override="${CLUSTER_ADMIN_PASSWORD}"
  fi

  info "Terraform init (destroy; backend path=${state_name})..."
  hcp_terraform_cmd init -input=false -backend-config="path=${state_name}" -reconfigure

  info "Terraform destroy..."
  local -a destroy_args=(destroy -input=false -auto-approve)
  # After partial destroy / interrupted apply, refresh can fail on empty data sources (e.g. cluster_default SGs).
  # Set ROSA_HCP_TERRAFORM_DESTROY_NO_REFRESH=1 to skip refresh (see README / benchmark-run-all).
  if [[ -n "${ROSA_HCP_TERRAFORM_DESTROY_NO_REFRESH:-}" ]]; then
    local __v
    __v="$(echo "${ROSA_HCP_TERRAFORM_DESTROY_NO_REFRESH}" | tr '[:upper:]' '[:lower:]' | tr -d '[:space:]')"
    if [[ "${__v}" == "1" || "${__v}" == "true" || "${__v}" == "yes" ]]; then
      destroy_args+=(-refresh=false)
      info "Using terraform destroy -refresh=false (ROSA_HCP_TERRAFORM_DESTROY_NO_REFRESH set)."
    fi
  fi
  [[ -n "${varfile}" ]] && destroy_args+=(-var-file="${varfile}")

  if ! hcp_terraform_cmd "${destroy_args[@]}"; then
    fail "terraform destroy failed. Fix errors or destroy resources in AWS/OCM manually."
  fi
  ok "Terraform destroy completed for cluster '${cluster}'."
}
